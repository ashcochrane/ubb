@pytest.mark.django_db
class TestACompensatingChargeIsNotProjected(ProjectionTestBase):
    """⚠ A NAMED RESIDUAL RATHER THAN AN OMISSION.

    `apps/billing/handlers.py` acts only on `billed_cost_micros > 0`, so a
    negative posting reaches the wallet, the period total and the live spend
    counter as nothing at all: a projected correction would look like a
    reversal and move no money. Correcting a charge ON THE RAILS needs a refund
    path rather than a negative posting, and that path is not this ticket's —
    `charge_service.compensate` has no route either, because a correction needs
    an operator surface and a record of who acted (#416).

    So the refusal is loud, and this class is what stops the gap being closed by
    accident: a later ticket that projects a correction has to delete an
    assertion that says why not.
    """

    def _a_correction_to(self, task_id):
        with transaction.atomic():
            return compensate(self._charges_against(task_id).get(),
                              note="the agreed price was wrong")

    def test_a_correction_is_refused_at_the_projection(self):
        started = self._priced_work()
        self._close(started)

        with pytest.raises(ValueError, match="compensating"):
            with transaction.atomic():
                project_the_charge(self._a_correction_to(started))

    def test_the_rails_would_have_ignored_it_anyway(self):
        """The measurement behind the refusal, so the sentence above is a
        finding rather than an opinion. A negative billed amount is below the
        handler's own guard, so nothing downstream of it runs — which is why
        refusing is better than projecting and hoping."""
        started = self._priced_work()
        self._close(started)
        self._drain_the_rails()
