"""The Charge projects onto exactly one marked posting, and that posting is
what reaches the money (#417, spec §12).

#416 made a delivered unit of work sold at one agreed price produce a canonical
`pricing.Charge` and said in its own module that the projected posting was not
its subject. This is that posting: **billed cost = the amount, provider cost =
zero, no measurement record, Grouping Fields inherited, `kind` = `task_charge`,
and no Event Type at all.**

**WHY A PROJECTION AND NOT A CANONICAL SYSTEM-GENERATED POSTING**, which is what
these cases are ultimately about:

* **Re-derivability.** A wrong posting can be rebuilt from the Charge; a wrong
  canonical event is permanent, because a posting is immutable AND undeletable.
* **The platform-fee effect is an EXPLICIT property of the projection** rather
  than something a synthetic row inherits by accident.
  `TestUbbsOwnFeeIsChargedOnTheProjection` proves what the fee is charged on by
  moving the period total the fee is a percentage of, rather than by reasoning
  from the fee formula.
* **Catalogue compatibility.** The posting is marked system-generated by its own
  discriminator instead of impersonating a recognised tenant Event Type, which
  would be unrecognised at the catalogue and quarantined.

⚠ **THE MONEY KEY IS THE POSTING'S ID, AND IT IS PRESERVED RATHER THAN
REPLACED.** The chain *unit of work → Charge → posting → deduction* is 1:1 at
every hop, so the wallet's `usage_deduction:{id}` key still names exactly one
movement of money, and the amount-mismatch guard in
`wallets/operations.py::draw_down_usage` still protects it.

⚠ **THE TWO ECONOMIC STATES THIS SLICE MAKES REACHABLE ARE NOT BOTH HERE.** This
module proves the `measurements_status` half — a charge posting reads as *not
applicable* rather than as a pruned metered one — because that state becomes
reachable the moment the discriminator lands and the derivation does the rest.
The metered postings UNDER a fixed-price unit of work reading `not_applicable`
rather than zero is #418's, and so is the receipt whose subject is a Charge.

⚠ **THE FIXTURE IS #416's, IMPORTED.** `docs/conventions/testing.md` wants
shared setup in one place, and the shape needed here is exactly the one that
module built — a tenant with a kind of work sold whole and one sold per event, a
wallet, and a close through the real route. Copying it would be two fixtures
free to drift into two ideas of what a priced unit of work is.
"""
