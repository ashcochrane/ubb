#: What a supplier charged for a projection: nothing, and settled. Spelled once
#: so a case asserting it says which of the column's two readings it means —
#: NULL is *not resolved* and this is *resolved, and it was exactly nothing*.
NO_SUPPLIER_WORK = 0

#: What one metered sale bills, when a case needs revenue from BOTH kinds and
#: needs them visibly different. Equal amounts would let a total that picked up
#: one of them twice read as correct.
A_METERED_SALE = 2_000_000


class ProjectionTestBase(ChargeTestBase):
    """#416's fixture, plus the readers this module needs on top of it."""

    def _projection_of(self, task_id):
        """The one posting the Charge for ``task_id`` projected onto."""
        return Posting.objects.get(task_id=task_id,
                                   kind=USAGE_EVENT_KIND_TASK_CHARGE)

    def _postings_on(self, task_id):
        return Posting.objects.filter(task_id=task_id)

    def _drain_the_rails(self):
        """Run every recorded posting through the real dispatcher.

        `dispatch_to_handlers` rather than the billing handler by name, because
        the dispatcher is what applies the PRODUCT GATE — and a metering-only
        tenant's rails are exactly the difference that gate makes. Calling the
        handler directly would run a billing lane for a tenant that does not
        have billing, and the one class in this module whose whole subject is
        that posture would have proved nothing.
        """
        for row in OutboxEvent.objects.filter(
                event_type="usage.recorded").order_by("created_at"):
            dispatch_to_handlers(row)

    def _a_metered_sale(self, task_id):
        """One metered posting under ``task_id``, and the posting it produced.

        ⚠ **WHETHER IT BILLS ANYTHING DEPENDS ON THE PIECE OF WORK IT IS UNDER,
        AND THAT IS #418'S RULE ARRIVING HERE.** Under work sold at one agreed
        price this posting's price is `not_applicable`, because the customer
        revenue is the whole piece's; under work priced per event it bills the
        amount below. The cases that need a metered posting merely to sit BESIDE
        a projection pass the fixed-price piece; the one that needs a second
        REVENUE in the tenant's period builds its own event-priced piece of work
        and passes that.
        """
        a_rule_that_prices_what_it_measures(self.tenant,
                                            event_type=SOLD_PER_EVENT)
        recorded = UsageService.record_usage(
            self.tenant, self.customer, f"call-{uuid.uuid4()}",
            event_type=SOLD_PER_EVENT, task_id=task_id,
            measurements=priced_at(A_METERED_SALE))
        return Posting.objects.get(id=recorded["event_id"])


