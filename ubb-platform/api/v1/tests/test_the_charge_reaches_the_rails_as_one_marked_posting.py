    """AC 2 — one posting, and every field of it is the one §12 names."""

    def test_a_delivered_priced_unit_of_work_produces_one_charge_posting(self):
        started = self._priced_work()

        self._close(started)

        assert self._postings_on(started).filter(
            kind=USAGE_EVENT_KIND_TASK_CHARGE).count() == 1

