"""The usage invoice line's grouped value takes the canonical noun (#312).

A pushed usage invoice line records the label its period's usage was grouped
under — the value of the axis the tenant's invoice-line grouping names. That
is the same thing the economic query calls `grouping_field_value`, so the
column that stores it says so too: on the table, on the model, and nowhere
under a name the registry retired.

**THE RETIRED NAME IS NEVER SPELLED HERE**, on the rule #274 and #275
established: a test module is a living surface, so spelling the word would
re-open the very extent #312 paid off, and the choice would then be a
hand-written exclusion or a false ledger count. It is read off the registry
that retired it — `grouping_field_value`'s `retired_aliases` — through
`api.v1.tests._helpers.retired_aliases`, and every retired spelling is held
absent, so a table or schema that grew any of them goes red here.

**The contract claim is an ABSENCE and it is checked in both directions.** This
column is internal: written in `postpaid_service`, read by this app's tests, and
published nowhere. That is what let a real column be renamed in a commit whose
whole point was that `openapi/v1.json` regenerated byte-identical — so "no schema
carries a retired name" is not a formality, it is the evidence for the claim.

Before the cutover (#190) this module also pinned `invoicing/0008`'s shape — a
hand-written `RenameField`, never an `AddField` beside a `RemoveField` (ADR-0007
§1), with a walk over nested operations and its two negative controls — and
drove that rename backwards and forwards over a written row. The squashed chain
creates the column under its final name, so there is no rename left to inspect;
what the rename left behind is pinned below.
"""

import json
import datetime

from django.core.exceptions import FieldDoesNotExist
from django.db import connection
from django.test import SimpleTestCase, TestCase

from api.v1.openapi_export import GIT_ROOT
from api.v1.tests._helpers import retired_aliases
from apps.billing.invoicing.models import CustomerUsageInvoice, UsageInvoiceLineItem
from apps.platform.customers.models import Customer
from apps.platform.tenants.models import Tenant

#: The canonical noun, which the economic query's row publishes too.
CANONICAL_COLUMN = "grouping_field_value"

#: Every spelling the registry retired for that noun — the line's old column
#: name among them — read off the registry, never written here.
RETIRED_NAMES = retired_aliases("economics", "grouping_field_value")


def _an_invoice():
    tenant = Tenant.objects.create(name="T")
    customer = Customer.objects.create(tenant=tenant, external_id="c1")
    return CustomerUsageInvoice.objects.create(
        tenant=tenant, customer=customer,
        period_start=datetime.date(2026, 6, 1), period_end=datetime.date(2026, 7, 1),
        total_billed_micros=1_000_000, currency="usd")


class TheTableAndTheModelBothMovedTest(TestCase):
    """Two separate claims, and only one of them is about the model.

    A field renamed on the model with no schema change behind it leaves the old
    column in the database, where a raw query would still find it — and the
    reverse, a schema change with no model change, leaves the model reading a
    column that is not there.
    """

    def test_the_table_carries_the_canonical_column_and_not_the_retired_one(self):
        with connection.cursor() as cursor:
            columns = {column.name for column in
                       connection.introspection.get_table_description(
                           cursor, UsageInvoiceLineItem._meta.db_table)}
        self.assertIn(CANONICAL_COLUMN, columns)
        for retired in RETIRED_NAMES:
            with self.subTest(retired=retired):
                self.assertNotIn(retired, columns)

    def test_the_retired_name_is_gone_from_the_model(self):
        for retired in RETIRED_NAMES:
            with self.subTest(retired=retired):
                with self.assertRaises(FieldDoesNotExist):
                    UsageInvoiceLineItem._meta.get_field(retired)

    def test_a_pushed_line_is_still_written_and_read_by_its_label(self):
        """The column is not merely present — the write path fills it.

        A column that left the service writing nothing would satisfy every
        structural assertion here and quietly empty every future invoice line.
        """
        invoice = _an_invoice()
        UsageInvoiceLineItem.objects.create(
            usage_invoice=invoice, amount_micros=600_000,
            **{CANONICAL_COLUMN: "prod_a"})
        self.assertEqual(
            list(invoice.line_items.values_list(CANONICAL_COLUMN, "amount_micros")),
            [("prod_a", 600_000)])


class TheContractIsWhereTheCanonicalNameCameFromTest(SimpleTestCase):
    """Why a real column could move in a zero-spec-diff commit — and where the
    word it moved to was already in use.

    Two claims, and they are not the same one twice. The ABSENCE is why the
    rename was not a contract change: nothing published carried the retired
    name, so the spec regenerated byte-identical. The PRESENCE is why the
    replacement was not invented for the line — a DECLARED schema already
    published the property, and its own comment states the reading this column
    rests on: it holds *the value the row groups, not the axis it was grouped
    on*. This column says what that schema has said all along.

    ⚠ **THE SCHEMA THAT SAID IT FIRST IS GONE (#501), AND THE PROPERTY IS NOT.**
    It was the grouped margin's row, one of three rollups over the same axes and
    the only one a drift gate could see; the one economic query's row declares
    the same property and is now the only publisher of it, which is a stronger
    place for this pin to point than it was when there were three.

    That makes this the pin under the ruling. If the published property is ever
    renamed, the sites that were deliberately spelled to match it are wrong, and
    this is where a reader finds that out.
    """

    PUBLISHED_ROW = "EconomicRowOut"

    @classmethod
    def setUpClass(cls):
        super().setUpClass()
        cls.schemas = json.loads(
            (GIT_ROOT / "openapi" / "v1.json").read_text(encoding="utf-8")
        )["components"]["schemas"]

    def test_no_published_schema_carries_the_retired_name(self):
        for name, schema in self.schemas.items():
            for retired in RETIRED_NAMES:
                with self.subTest(schema=name, retired=retired):
                    self.assertNotIn(retired, schema.get("properties", {}))

    def test_the_declared_margin_row_publishes_the_canonical_name(self):
        self.assertIn(CANONICAL_COLUMN,
                      self.schemas[self.PUBLISHED_ROW]["properties"])
